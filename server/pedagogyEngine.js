/**
 * Función que segmenta la transcripción en episodios didácticos
 */
export function segmentarEpisodios(lineas) {
  if (!lineas || !lineas.length) return [];
  const n = lineas.length;
  
  // Si son pocas líneas, un solo episodio
  if (n <= 10) {
    return [{
      ini: 1,
      fin: n,
      tipo: "explicacion",
      titulo: "Intervención de aula",
      resumen: "Clase completa registrada."
    }];
  }

  const episodios = [];
  const chunkSize = Math.max(8, Math.floor(n / 6));
  let start = 1;

  const tiposSecuencia = [
    { tipo: "presentacion_tarea", titulo: "Inicio y planteamiento de la tarea", resumen: "Presentación del propósito matemático y consignas iniciales." },
    { tipo: "discusion", titulo: "Exploración de estrategias y discusión", resumen: "Intercambio en torno a procedimientos de resolución e interpretación de respuestas." },
    { tipo: "error", titulo: "Tratamiento de dificultades y errores", resumen: "Abordaje de inconsistencias conceptuales o procedimientos divergentes." },
    { tipo: "explicacion", titulo: "Institucionalización y conexiones", resumen: "Formalización de conceptos matemáticos y representaciones en la pizarra." },
    { tipo: "trabajo_estudiantes", titulo: "Aplicación y debate entre pares", resumen: "Trabajo en parejas o individual y monitoreo de desempeño." },
    { tipo: "cierre", titulo: "Síntesis y cierre matemático", resumen: "Resumen de ideas centrales y verificación formativa final." }
  ];

  for (let i = 0; i < tiposSecuencia.length; i++) {
    const end = (i === tiposSecuencia.length - 1) ? n : Math.min(n, start + chunkSize);
    if (start <= n) {
      episodios.push({
        ini: start,
        fin: end,
        tipo: tiposSecuencia[i].tipo,
        titulo: tiposSecuencia[i].titulo,
        resumen: tiposSecuencia[i].resumen
      });
      start = end + 1;
    }
  }

  return episodios;
}

